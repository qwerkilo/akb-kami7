"""产物写出：members.js / bios.js / simplified.js 与未使用图片清理。

从 fetch_members 抽出，保持生成的字节格式与文件头不变（产物测试按字节/结构校验）。
"""
import json
import os


def write_members_js(sections, path):
    """写 members.js（无 bio）+ 同目录 bios.js（id → 简介）。

    简介占产物 ~106KB，而首屏只需姓名/图像/状态；拆出去后首页少解析这些字节，
    bios.js 由 app.js 空闲预取（离线靠 SW 壳缓存）。结构守卫见
    test/members-artifact.test.js（members.js 不许有 bio / bios 覆盖全部 id）。
    """
    stripped = []
    bios = {}
    for sec in sections:
        members = []
        for m in sec["members"]:
            item = dict(m)
            bios[item["id"]] = item.pop("bio", None) or {}
            members.append(item)
        stripped.append({**sec, "members": members})
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("// generated by scripts/fetch_members.py from 48pedia.org\n")
        fh.write("window.AKB_GROUPS = ")
        json.dump(stripped, fh, ensure_ascii=False, indent=1)
        fh.write(";\n")
    with open(os.path.join(os.path.dirname(path), "bios.js"), "w", encoding="utf-8") as fh:
        fh.write("// generated by scripts/fetch_members.py from 48pedia.org\n")
        fh.write("window.AKB_BIOS = ")
        # 纯查表数据、不参与 diff 评审：紧凑写，省 ~30KB
        json.dump(bios, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")


def build_simplified(names, convert=None):
    """Return {simplified: [source forms...]} for name chars that need folding."""
    if convert is None:
        try:
            from opencc import OpenCC
        except ImportError:
            print("warning: 未安装 opencc，跳过 simplified.js 生成（pip install opencc）")
            return None
        t2s = OpenCC("t2s")
        try:
            jp2t = OpenCC("jp2t")
        except Exception:
            jp2t = None
        convert = (lambda ch: t2s.convert(jp2t.convert(ch))) if jp2t else t2s.convert
    pairs = {}
    for name in names:
        for ch in name:
            sim = convert(ch)
            if sim != ch:
                forms = pairs.setdefault(sim, [])
                if ch not in forms:
                    forms.append(ch)
    return pairs


def write_simplified_js(pairs, path):
    body = json.dumps(pairs, ensure_ascii=False, separators=(",", ":"))
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("// generated by scripts/fetch_members.py from 48pedia.org\n")
        fh.write(f"window.AKB_SIMPLIFIED = {body};\n")


def prune_unused(keep, dirs):
    removed = 0
    for d in dirs:
        for fn in os.listdir(d):
            if os.path.splitext(fn)[0] not in keep:
                os.remove(os.path.join(d, fn))
                removed += 1
    return removed


